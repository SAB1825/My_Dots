#!/usr/bin/env python3
"""Generate a Brave theme; optionally sync the built-in NTP with Brave closed."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
CONFIG = Path.home() / '.config'


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(dir=path.parent, prefix=f'.{path.name}.')
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(text)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def read_palette(from_gtk=False):
    if not from_gtk and (ROOT / 'palette.json').exists():
        palette = json.loads((ROOT / 'palette.json').read_text())
    else:
        css = (CONFIG / 'session/theme-sync/generated.css').read_text()
        colors = dict(re.findall(r'@define-color\s+(\w+)\s+(#[0-9a-fA-F]{6})\s*;', css))
        palette = {key: colors[name] for key, name in {
            'background': 'theme_bg_color', 'foreground': 'theme_fg_color',
            'field': 'theme_base_color', 'muted': 'theme_unfocused_fg_color',
            'accent': 'accent_color',
        }.items()}
    for key in ('background', 'foreground', 'field', 'muted', 'accent'):
        if not re.fullmatch(r'#[0-9a-fA-F]{6}', palette[key]):
            raise ValueError(f'Invalid color for {key}')
    return palette


def rgb(hex_color):
    return [int(hex_color[i:i + 2], 16) for i in (1, 3, 5)]


def sync_new_tab(background):
    # Never edit Preferences while Brave can overwrite it from memory.
    running = subprocess.run(['pgrep', '-u', str(os.getuid()), '-x', 'brave'],
                             stdout=subprocess.DEVNULL)
    if running.returncode != 1:
        raise RuntimeError('Close Brave completely first (including background processes), then rerun this command.')
    path = CONFIG / 'BraveSoftware/Brave-Browser/Default/Preferences'
    original = path.read_text()
    prefs = json.loads(original)
    ntp = prefs.setdefault('brave', {}).setdefault('new_tab_page', {})
    ntp['background'] = {'random': False, 'selected_value': background, 'type': 'color'}
    ntp['show_background_image'] = True
    backup = path.with_name('Preferences.before-matugen-theme')
    if not backup.exists():
        atomic_write(backup, original)
    atomic_write(path, json.dumps(prefs, separators=(',', ':')))
    print(f'Brave Default-profile new-tab background: {background}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--from-gtk', action='store_true', help='Use the currently generated GTK palette')
    parser.add_argument('--sync-new-tab', action='store_true', help='Update the Default profile; requires Brave to be closed')
    args = parser.parse_args()
    palette = read_palette(args.from_gtk)
    bg, fg, field, muted, accent = (rgb(palette[key]) for key in
                                   ('background', 'foreground', 'field', 'muted', 'accent'))
    manifest = {
        'manifest_version': 3, 'name': 'Matugen Wallpaper', 'version': '1.0.0',
        'description': 'Wallpaper colors generated by Matugen. Reload after palette changes.',
        'theme': {'colors': {
            'frame': bg, 'frame_inactive': bg, 'toolbar': bg,
            'tab_text': fg, 'tab_background_text': muted,
            'tab_background_text_inactive': muted, 'bookmark_text': fg,
            'toolbar_text': fg, 'toolbar_button_icon': fg,
            'omnibox_background': field, 'omnibox_text': fg,
            'ntp_background': bg, 'ntp_text': fg, 'ntp_link': accent,
        }},
    }
    atomic_write(ROOT / 'theme/manifest.json', json.dumps(manifest, indent=2) + '\n')
    atomic_write(ROOT / 'current-background.txt', palette['background'] + '\n')
    print(f'Theme generated: {ROOT / "theme"} (background {palette["background"]})')
    if args.sync_new_tab:
        sync_new_tab(palette['background'])


if __name__ == '__main__':
    main()
